"""Generate the Moto G10 embedded device-tree header."""

import argparse
import struct
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dtb", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    data = args.dtb.read_bytes()
    if len(data) < 40 or data[:4] != b"\xd0\x0d\xfe\xed":
        parser.error("input is not a flattened device tree")
    size = struct.unpack_from(">I", data, 4)[0]
    if size != len(data) or size >= 128 * 1024:
        parser.error("DTB size must match its header and fit the 128 KiB buffer")
    if b"motorola,capri\0" not in data:
        parser.error("input is not the Motorola Moto G10 device tree")
    text = "/* Generated by scripts/capri/embed-dtb.py. */\n"
    text += "static const unsigned char capri_dtb[] __initconst __aligned(8) = {\n"
    text += "".join("\t" + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ",\n"
                    for i in range(0, len(data), 16))
    text += "};\n"
    args.header.parent.mkdir(parents=True, exist_ok=True)
    if not args.header.exists() or args.header.read_text() != text:
        args.header.write_text(text)
    print(f"Embedded {len(data)} DTB bytes in {args.header}")


if __name__ == "__main__":
    main()
